import { expect, test } from "@playwright/test";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";

test("source review, immutable spec, code preview and measured fixture export", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("/");
  await expect(page.getByText("Local API connected", { exact: true })).toBeVisible();
  const accessCode = readFileSync(resolve(process.cwd(), "../../data/e2e/access-code.txt"), "utf8");
  await page.getByLabel("Local access code").fill(accessCode);
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await page.getByRole("button", { name: "Use demonstration PDF" }).click();
  await page.locator(".passage").filter({ hasText: "Randomized Kaczmarz is tested" }).click();
  await page.getByLabel("Method supported by this passage").selectOption("randomized_kaczmarz");
  await page.getByRole("button", { name: "Save sourced claim" }).click();
  const editor = page.getByLabel("Experiment specification (JSON)");
  await expect(editor).toBeVisible();
  await page.getByRole("button", { name: "Save specification", exact: true }).click();
  await expect(page.getByText("A target and explicit rationale must be supplied before approval.", { exact: true })).toBeVisible();
  await expect(page.getByRole("checkbox")).toBeDisabled();
  const draft = JSON.parse(await editor.inputValue());
  draft.target_relative_error = 0.01;
  draft.target_rationale = "Browser test: approved engineering threshold, not a paper finding.";
  await editor.fill(JSON.stringify(draft, null, 2));
  await page.getByRole("button", { name: "Save as a new version" }).click();
  await expect(page.getByRole("button", { name: /Version 2/ })).toBeVisible();
  await page.getByRole("checkbox").check();
  await page.getByRole("button", { name: "Stage offline code preview" }).click();
  await expect(page.getByRole("heading", { name: "awaiting sandbox", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Inspect staged code" }).click();
  await expect(page.locator(".code-view")).toContainText("def solve(payload");
  await expect(page.getByText("OFFLINE FIXTURE TEMPLATE · not Meta-generated · not executed", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Run reviewed engineering fixture" }).click();
  await expect(page.getByRole("heading", { name: "completed", exact: true })).toBeVisible();
  await expect(page.getByText("fixture_target_met", { exact: true })).toBeVisible();
  await expect(page.locator("tbody tr")).toHaveCount(3);
  const values = await page.locator("tbody tr td:nth-child(2)").allTextContents();
  expect(values.every(value => Number(value) < 0.01)).toBeTruthy();
  const downloadPromise = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download evidence ZIP" }).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toMatch(/^paper2proof-.*\.zip$/);
  await page.screenshot({ path: "../../artifacts/browser-workspace.png", fullPage: true });
  await page.getByRole("button", { name: "Delete paper", exact: true }).click();
  await page.getByRole("button", { name: "Confirm delete", exact: true }).click();
  await expect(page.locator(".source-grid")).toHaveCount(0);
  expect(errors).toEqual([]);
});
